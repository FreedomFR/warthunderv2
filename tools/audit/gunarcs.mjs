// What each defensive gun of an aircraft can really bear on: from the muzzle of every gun position, a ray along every direction of its field of fire is cast against the drawn aircraft (fuselage,
// wings, tail, engines: the model/planes.js mesh of the whole aircraft); a direction is blocked when the ray meets the aircraft before it is clear of it. Prints, for each position, the part of the
// field of fire that is blocked and where (yaw x pitch), so that the fields of planeGuns.js can be set to what is free.
//   node tools/audit/gunarcs.mjs [type,type...] [--grid] [--write]     (--grid draws the field of each position as a map; --write makes js/game/data/gunmasks.js: what is blocked, cell by cell, for the sim)
import { PLANES, drawPlane } from '../../js/game/model/planes.js';
import { MeshBuilder } from '../../js/game/model/meshbuilder.js';
import { planeGuns, inField, muzzleOf } from '../../js/game/model/planeGuns.js';
import fs from 'node:fs';

const args = process.argv.slice(2), grid = args.includes('--grid'), write = args.includes('--write'), check = args.includes('--check'), only = (args.find((a) => !a.startsWith('--')) || '').split(',').filter(Boolean);
const D = Math.PI / 180;

function meshOf(key) {
  const spec = PLANES[key], b = new MeshBuilder();
  drawPlane(b, spec, { part: 'whole' });
  return { P: b.p, I: b.idx };
}

/** Does the ray from o along u meet a triangle of the mesh at a distance between t0 and t1? (Moeller-Trumbore) */
function hits(m, o, u, t0, t1) {
  const P = m.P, I = m.I;
  for (let i = 0; i < I.length; i += 3) {
    const a = I[i] * 3, b = I[i + 1] * 3, c = I[i + 2] * 3;
    const e1x = P[b] - P[a], e1y = P[b + 1] - P[a + 1], e1z = P[b + 2] - P[a + 2], e2x = P[c] - P[a], e2y = P[c + 1] - P[a + 1], e2z = P[c + 2] - P[a + 2];
    const px = u[1] * e2z - u[2] * e2y, py = u[2] * e2x - u[0] * e2z, pz = u[0] * e2y - u[1] * e2x;
    const det = e1x * px + e1y * py + e1z * pz;
    if (Math.abs(det) < 1e-9) continue;
    const id = 1 / det, tx = o[0] - P[a], ty = o[1] - P[a + 1], tz = o[2] - P[a + 2];
    const s = (tx * px + ty * py + tz * pz) * id;
    if (s < 0 || s > 1) continue;
    const qx = ty * e1z - tz * e1y, qy = tz * e1x - tx * e1z, qz = tx * e1y - ty * e1x;
    const v = (u[0] * qx + u[1] * qy + u[2] * qz) * id;
    if (v < 0 || s + v > 1) continue;
    const t = (e2x * qx + e2y * qy + e2z * qz) * id;
    if (t > t0 && t < t1) return true;
  }
  return false;
}

const keys = Object.keys(PLANES).filter((k) => (!only.length || only.includes(k)) && planeGuns(PLANES[k], k).length);
const masks = {};
for (const key of keys) {
  const spec = PLANES[key], guns = planeGuns(spec, key), m = meshOf(key);
  for (const g of guns) {
    let tot = 0, blocked = 0;
    const rows = [], bad = [], list = [];
    // the cells of 5 degrees (their centres are the directions cast): from straight up to straight down, round the horizon
    for (let p = 87.5; p > -90; p -= 5) {
      let row = '', run = null;
      for (let y = -177.5; y < 180; y += 5) {
        if (!inField(g, y * D, p * D)) { row += ' '; if (run) { list.push([p - 2.5, run[0], run[1]]); run = null; } continue; }
        tot++;
        const mz = muzzleOf(g, y * D, p * D), u = [Math.cos(p * D) * Math.cos(y * D), Math.sin(p * D), Math.cos(p * D) * Math.sin(y * D)];
        // (from a little ahead of the muzzle: the barrel itself and its housing are not what blocks it)
        const o = [mz[0] + u[0] * 0.05, mz[1] + u[1] * 0.05, mz[2] + u[2] * 0.05];
        const hit = hits(m, o, u, 0.02, 40);
        if (hit) { blocked++; bad.push([y, p]); if (run) run[1] = y + 2.5; else run = [y - 2.5, y + 2.5]; } else if (run) { list.push([p - 2.5, run[0], run[1]]); run = null; }
        row += hit ? '#' : '.';
      }
      if (run) list.push([p - 2.5, run[0], run[1]]);
      if (row.trim()) rows.push(`${String(p).padStart(5)} ${row}`);
    }
    if (list.length) (masks[key] ||= {})[g.id] = list;
    const pct = tot ? (blocked / tot * 100) : 0;
    console.log(`${key} ${g.t}[${g.id}] cal ${g.cal} n ${g.n}: ${tot} cells in the field, ${blocked} blocked (${pct.toFixed(0)} %)${bad.length ? '  e.g. yaw ' + bad.slice(0, 4).map((q) => q.join('/')).join(' ') : ''}`);
    if (grid) { console.log('       ' + [-180, -120, -60, 0, 60, 120].map((y) => String(y).padEnd(12)).join('')); for (const r of rows) console.log(r); }
  }
}
if (write || check) {
  const lines = Object.entries(masks).map(([k, v]) => `  ${k}: { ${Object.entries(v).map(([id, l]) => `${id}: ${JSON.stringify(l)}`).join(', ')} },`);
  const text = `// The directions that the aircraft's own structure blocks for each defensive gun position: { type: { position id: [[pitch, yaw from, yaw to], ...] } } in degrees, in cells of 5 degrees.\n// Generated by \`node tools/audit/gunarcs.mjs --write\` (a test fails when it is stale).\nexport const GUN_MASKS = {\n${lines.join('\n')}\n};\n`;
  const file = new URL('../../js/game/data/gunmasks.js', import.meta.url);
  if (write) { fs.writeFileSync(file, text); console.log('written ' + lines.length + ' types'); }
  else if (fs.readFileSync(file, 'utf8') !== text) { console.log('FAIL gunmasks.js is stale: run node tools/audit/gunarcs.mjs --write'); process.exitCode = 1; }
  else console.log('PASS gunmasks.js is up to date (' + lines.length + ' types)');
}

// The baked reference model (tools/refs/bake.py) cut into the pieces the game draws and packed into a JS module (js/game/model/ships/<id>_baked.js):
//   node tools/refs/bakepack.mjs <bakeddir> <mounts.json> <out.js> [--tower=x0,x1,y0] [--funnel=x0,x1,hw,y0]
// Triangles on a mount that the game draws itself (turret houses and barrels, cupolas, AA mounts: discs and corridors from mounts.json) are left out; the rest goes to the piece `tower`
// (the destroyable bridge), `funnel` or `static`. Positions are quantised to 5 mm, colours are the texture colours at the vertices; the normals are computed when the module is read.
import fs from 'node:fs';
import path from 'node:path';

const a = process.argv.slice(2), pos = a.filter((x) => !x.startsWith('--')), fl = Object.fromEntries(a.filter((x) => x.startsWith('--')).map((x) => { const [k, v] = x.slice(2).split('='); return [k, v ?? '1']; }));
const [dir, mountsFile, outFile] = pos;
const info = JSON.parse(fs.readFileSync(path.join(dir, 'info.json'), 'utf8'));
const rd = (f, T) => { const b = fs.readFileSync(path.join(dir, f)); return new T(b.buffer, b.byteOffset, b.byteLength / T.BYTES_PER_ELEMENT); };
const P = rd('pos.f32', Float32Array), C = rd('col.u8', Uint8Array), I = rd('idx.u32', Uint32Array);
const mounts = JSON.parse(fs.readFileSync(mountsFile, 'utf8'));
const tw = (fl.tower || '-8,16,18').split(',').map(Number), fu = (fl.funnel || '-33,-12,5,14').split(',').map(Number);

const masked = (x, y, z) => {
  for (const m of mounts) {
    const r = m.g === 'main' ? 9.5 : m.cal === 155 ? 5.6 : m.g === 'sec' ? 4.0 : 3.2;
    if (y > m.y - 0.3 && Math.hypot(x - m.x, z - m.z) < r) return true;
    // the barrels of the turrets, which the game draws as guns
    if (m.g === 'main' || m.cal === 155) {
      const dir = m.x < -40 ? -1 : 1, u = (x - m.x) * dir;
      const [u0, u1, hw] = m.g === 'main' ? [8, 26, 5] : [3, 11, 2.4];
      if (u > u0 && u < u1 && Math.abs(z - m.z) < hw && y > m.y - 0.5) return true;
    }
  }
  return false;
};

const pieces = { static: [], tower: [], funnel: [] };
let dropped = 0;
for (let t = 0; t < I.length; t += 3) {
  const a0 = I[t], a1 = I[t + 1], a2 = I[t + 2];
  const x = (P[a0 * 3] + P[a1 * 3] + P[a2 * 3]) / 3, y = (P[a0 * 3 + 1] + P[a1 * 3 + 1] + P[a2 * 3 + 1]) / 3, z = (P[a0 * 3 + 2] + P[a1 * 3 + 2] + P[a2 * 3 + 2]) / 3;
  if (masked(x, y, z)) { dropped++; continue; }
  const k = (y >= tw[2] && x > tw[0] && x < tw[1]) ? 'tower' : (y >= fu[3] && x > fu[0] && x < fu[1] && Math.abs(z) < fu[2]) ? 'funnel' : 'static';
  pieces[k].push(t);
}
console.error(`dropped ${dropped} triangles on the mounts; ${Object.entries(pieces).map(([k, v]) => `${k} ${v.length}`).join(', ')}`);

const SC = 200;                                                                       // 5 mm
const out = {};
for (const [name, tris] of Object.entries(pieces)) {
  const map = new Map(), vp = [], vc = [], ix = [];
  for (const t of tris) for (let q = 0; q < 3; q++) {
    const v = I[t + q];
    if (!map.has(v)) { map.set(v, vp.length / 3); vp.push(Math.round(P[v * 3] * SC), Math.round(P[v * 3 + 1] * SC), Math.round(P[v * 3 + 2] * SC)); vc.push(C[v * 3], C[v * 3 + 1], C[v * 3 + 2]); }
    ix.push(map.get(v));
  }
  const b64 = (arr) => Buffer.from(arr.buffer, arr.byteOffset, arr.byteLength).toString('base64');
  out[name] = { nv: vp.length / 3, ni: ix.length, pos: b64(new Int16Array(vp)), col: b64(new Uint8Array(vc)), idx: b64(ix.length && Math.max(...[ix[0]]) >= 0 && vp.length / 3 < 65536 ? new Uint16Array(ix) : new Uint32Array(ix)), wide: vp.length / 3 >= 65536 };
}
const head = `// The Yamato's solid masses read on the reference model (KojfDiscord, CC BY 4.0: see docs/CREDITS.md): its triangles simplified to ${Math.round(I.length / 3 / 1000)}k, the colour of its textures at every vertex, cut into the destroyable\n// pieces. Generated by tools/refs/bake.py + bakepack.mjs; read by ships/yamato.js (decodeBaked). Positions in 5 mm steps, game frame (x bow +, y over the waterline, z starboard).\nexport const SCALE = ${SC};\nexport const BAKED = `;
fs.writeFileSync(outFile, head + JSON.stringify(out) + ';\n');
console.error(`${outFile}: ${(fs.statSync(outFile).size / 1e6).toFixed(2)} MB`);

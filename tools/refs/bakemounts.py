#!/usr/bin/env python3
"""The gun houses and gun barrels of a reference model baked for the game's mount families (js/game/model/mounts.js): the triangles of one mount of each kind, in the mount's own frame, simplified.

  python3 tools/refs/bakemounts.py refs/<id>/bake tools/refs/<id>_mounts_bake.json js/game/model/ships/<id>_mounts_baked.js

The JSON is a list of { name, pivot: [x, z, y] (the training axis, game metres), yaw (deg, 0 = ahead, 90 = starboard), house: { u: [u0, u1], w, y: [y0, y1] } (what belongs to the gun house, in the mount frame:
u forward, w to starboard, y over the pivot), guns: { u: [u0, u1], w, y: [y0, y1] } (the barrels, drawn as the guns mesh, cut at u0, origin at (u0, axis)), axis (barrel axis over the pivot), tris: [house, guns] }.
Needs numpy and open3d (bake.py has written colfull.u8 in the bake directory).
"""
import sys, json, os
import numpy as np
import open3d as o3d

src, cfgf, outf = sys.argv[1:4]
info = json.load(open(os.path.join(src, 'info.json')))
nv, nf = info['vertices'], info['triangles']
P = np.fromfile(os.path.join(src, 'pos.f32'), dtype=np.float32).reshape(nv, 3)
C = np.fromfile(os.path.join(src, 'colfull.u8'), dtype=np.uint8).reshape(nv, 3)
I = np.fromfile(os.path.join(src, 'idx.u32'), dtype=np.uint32).reshape(nf, 3)
cfg = json.load(open(cfgf))
SC = 400


def piece(sel_mask, T, loc, target, shift):
    tris = I[sel_mask]
    if len(tris) == 0:
        return None
    used = np.unique(tris)
    remap = -np.ones(nv, dtype=np.int64); remap[used] = np.arange(len(used))
    m = o3d.geometry.TriangleMesh()
    m.vertices = o3d.utility.Vector3dVector((loc[used] - shift).astype(np.float64))
    m.triangles = o3d.utility.Vector3iVector(remap[tris].astype(np.int32))
    m.vertex_colors = o3d.utility.Vector3dVector(C[used].astype(np.float64) / 255.0)
    m.merge_close_vertices(0.01); m.remove_degenerate_triangles(); m.remove_duplicated_triangles(); m.remove_unreferenced_vertices()
    if len(m.triangles) > target:
        m = m.simplify_quadric_decimation(target_number_of_triangles=target)
        m.remove_degenerate_triangles(); m.remove_unreferenced_vertices()
    pos = np.asarray(m.vertices, dtype=np.float32)
    col = (np.clip(np.asarray(m.vertex_colors), 0, 1) * 255).astype(np.uint8)
    idx = np.asarray(m.triangles, dtype=np.uint32)
    return pos, col, idx


def b64(a):
    import base64
    return base64.b64encode(a.tobytes()).decode()


out = {}
for c in cfg:
    cx, cz, py = c['pivot']
    yaw = np.radians(c['yaw'])
    cs, sn = np.cos(yaw), np.sin(yaw)
    dx, dz = P[:, 0] - cx, P[:, 2] - cz
    loc = np.stack([dx * cs + dz * sn, P[:, 1] - py, -dx * sn + dz * cs], axis=1)           # u (forward), y over the pivot, w (starboard)
    cen = loc[I].mean(axis=1)
    entry = {}
    for kind in ('house', 'guns'):
        r = c.get(kind)
        if not r:
            continue
        sel = (cen[:, 0] >= r['u'][0]) & (cen[:, 0] <= r['u'][1]) & (np.abs(cen[:, 2]) <= r['w']) & (cen[:, 1] >= r['y'][0]) & (cen[:, 1] <= r['y'][1])
        shift = np.array([r['u'][0], c['axis'], 0.0]) if kind == 'guns' else np.zeros(3)
        res = piece(sel, None, loc, c['tris'][0 if kind == 'house' else 1], shift)
        if res is None:
            print(c['name'], kind, 'nothing', file=sys.stderr); continue
        pos, col, idx = res
        q = np.round(pos * SC).astype(np.int16)
        entry[kind] = {'nv': int(len(pos)), 'ni': int(idx.size), 'pos': b64(q), 'col': b64(col), 'idx': b64(idx.astype(np.uint16) if len(pos) < 65536 else idx), 'wide': len(pos) >= 65536}
        print(f"{c['name']} {kind}: {len(idx)} triangles, {len(pos)} vertices", file=sys.stderr)
    out[c['name']] = entry
head = "// The gun houses and barrels of the Yamato's mount families read on the reference model (KojfDiscord, CC BY 4.0: docs/CREDITS.md): one mount of each kind in its own frame, simplified, the texture colours at the vertices.\n// Generated by tools/refs/bakemounts.py; read by model/mounts.js (bakedMount). Positions in 2.5 mm steps; house: origin at the training axis; guns: origin at the cut / barrel axis.\nexport const MOUNT_SCALE = %d;\nexport const MOUNTS_BAKED = " % SC
open(outf, 'w').write(head + json.dumps(out) + ';\n')
print(f'{outf}: {os.path.getsize(outf) / 1e6:.2f} MB', file=sys.stderr)
